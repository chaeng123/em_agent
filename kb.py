def detect_emergency(text: str) -> bool:
    """위급 신호 감지."""
    return any(k in text for k in EMERGENCY_SIGNS)


def match_conditions(text: str):
    """입력 텍스트와 키워드가 겹치는 질환을 (질환id, 매칭키워드) 리스트로 반환.
    매칭 키워드 수가 많은 순으로 정렬."""
    scored = []
    for cid, c in CONDITIONS.items():
        hits = [k for k in c["keywords"] if k in text]
        if hits:
            scored.append((len(hits), cid, hits))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [(cid, hits) for _, cid, hits in scored]
