def match_presentations(text: str):
    """입력 텍스트에서 일치하는 증상 클러스터 목록을 반환(매칭 키워드 수 내림차순)."""
    matched = []
    for p in PRESENTATIONS:
        hits = [k for k in p["keywords"] if k in text]
        if hits:
            matched.append((len(hits), p, hits))
    matched.sort(key=lambda x: x[0], reverse=True)
    return [(p, hits) for _, p, hits in matched]
